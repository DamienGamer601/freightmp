const { contextBridge, ipcRenderer } = require("electron");

contextBridge.exposeInMainWorld("freightmp", {
  loadConfig: () => ipcRenderer.invoke("config:load"),
  saveConfig: (config) => ipcRenderer.invoke("config:save", config),
  detectGames: () => ipcRenderer.invoke("games:detect"),
  fetchServers: () => ipcRenderer.invoke("servers:fetch"),
  fetchNews: () => ipcRenderer.invoke("news:fetch"),
  fetchFriends: () => ipcRenderer.invoke("friends:fetch"),
  fetchProfile: () => ipcRenderer.invoke("profile:fetch"),
  gameStatus: () => ipcRenderer.invoke("game:status"),
  fetchPlayers: () => ipcRenderer.invoke("players:fetch"),
  checkUpdate: () => ipcRenderer.invoke("update:check"),
  openUpdate: (url) => ipcRenderer.invoke("update:open", url),
  applyUpdate: () => ipcRenderer.invoke("update:apply"),
  apiGet: (path) => ipcRenderer.invoke("api:get", path),
  setEnvironment: (payload) => ipcRenderer.invoke("mp:setEnvironment", payload),
  getRoom: (roomId) => ipcRenderer.invoke("mp:getRoom", roomId),
  apiPatch: (path, body) => ipcRenderer.invoke("api:patch", { path, body }),
  apiPost: (path, body) => ipcRenderer.invoke("api:post", { path, body }),
  linkAccount: (provider) => ipcRenderer.invoke("auth:link", provider),
  unlinkAccount: (provider) => ipcRenderer.invoke("auth:unlink", provider),
  logout: () => ipcRenderer.invoke("auth:logout"),
  notify: (title, body) => ipcRenderer.invoke("notify:show", { title, body }),
  writeLog: (message) => ipcRenderer.invoke("log:write", message),
  readLogs: () => ipcRenderer.invoke("logs:read"),
  clearLogs: () => ipcRenderer.invoke("logs:clear"),
  clientVersion: () => ipcRenderer.invoke("client:version"),
  listPlugins: () => ipcRenderer.invoke("plugins:list"),
  onTrayPlay: (callback) => ipcRenderer.on("tray:play", callback),
  openConfigFolder: () => ipcRenderer.invoke("app:openConfigFolder"),
  appPaths: () => ipcRenderer.invoke("app:paths"),
  openSite: () => ipcRenderer.invoke("site:open"),
  login: () => ipcRenderer.invoke("login"),
  launch: (params) => ipcRenderer.invoke("launch", params),
});
